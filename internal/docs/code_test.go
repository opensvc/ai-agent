const speakerFile = `package nmon

// updateSpeaker elects the speaking node: the leader of the cluster, which
// reports to the collector and holds the cluster locks.
func (t *Manager) updateSpeaker() {
	t.speaker = t.speakerNode()
}

// speakerNode return the speaker node: the first alive node from
// clusterConfig.Nodes.
func (t *Manager) speakerNode() string {
	for _, nodename := range t.clusterConfig.Nodes {
		if _, ok := t.livePeers[nodename]; ok {
			return nodename
		}
	}
	return ""
}
`

const waitFile = `package imon

// bootStartWaitMax bounds the wait of the boot start on a busy peer.
var bootStartWaitMax = 5 * time.Minute
`

func codeIndex(t *testing.T, files ...File) *CodeIndex {
	t.Helper()
	x, err := NewCode(files, "the test code")
	if err != nil {
		t.Fatal(err)
	}
	return x
}

func TestNewCodeLeavesOutTestsGeneratedCodeAndWhatDoesNotParse(t *testing.T) {
	x := codeIndex(t,
		File{Path: "daemon/nmon/speaker.go", Text: speakerFile},
		File{Path: "daemon/nmon/speaker_test.go", Text: "package nmon\n\nfunc TestSpeaker() {}\n"},
		File{Path: "daemon/api/codegen_gen.go", Text: "// Code generated by oapi-codegen. DO NOT EDIT.\npackage api\n\nfunc Generated() {}\n"},
		File{Path: "broken.go", Text: "package x\n\nfunc {"},
		File{Path: "README.md", Text: "# readme"},
	)
	if x.Len() != 2 || x.Parents() != 1 || x.Skipped != 2 {
		t.Errorf("chunks %d, parents %d, skipped %d", x.Len(), x.Parents(), x.Skipped)
	}
}

// TestCodeSearchGivesTheFileOfAShortDeclaration finds the words of a question
// in the comment of one function and gives the whole short file, the small
// function next to it, which holds the answer, included.
func TestCodeSearchGivesTheFileOfAShortDeclaration(t *testing.T) {
	x := codeIndex(t, File{Path: "daemon/nmon/speaker.go", Text: speakerFile}, File{Path: "daemon/imon/wait.go", Text: waitFile})
	found, err := x.Search("cluster leader election speaking node collector locks", 3)
	if err != nil || len(found) != 1 {
		t.Fatalf("found %+v, %v", found, err)
	}
	if found[0].Path != "daemon/nmon/speaker.go" || found[0].Start != 3 || found[0].End != 18 || !strings.Contains(found[0].Text, "first alive node") {
		t.Errorf("result %s:%d-%d %q", found[0].Path, found[0].Start, found[0].End, found[0].Text)
	}
	// The words of an identifier are searched: bootStartWaitMax is boot
	// start wait max.
	found, err = x.Search("boot start wait max", 3)
	if err != nil || len(found) == 0 || found[0].Path != "daemon/imon/wait.go" {
		t.Errorf("found %+v, %v", found, err)
	}
	if _, err := x.Search("speaker", 9); err == nil {
		t.Error("a limit of 9 was taken")
	}
}

// TestNewCodePacksALongFileInRunsOfDeclarations cuts a file longer than a
// parent in runs of its declarations, and a declaration longer than a chunk
// in parts of its lines.
func TestNewCodePacksALongFileInRunsOfDeclarations(t *testing.T) {
	var b strings.Builder
	b.WriteString("package big\n\n")
	for i := 0; i < 40; i++ {
		b.WriteString("// f" + strings.Repeat("x", 2) + " does a thing.\nfunc F" + string(rune('A'+i%26)) + strings.Repeat("y", i) + "() {\n\t_ = \"" + strings.Repeat("z", 300) + "\"\n}\n\n")
	}
	b.WriteString("func Long() {\n")
	for i := 0; i < 400; i++ {
		b.WriteString("\t_ = \"" + strings.Repeat("w", 40) + "\"\n")
	}
	b.WriteString("}\n")
	x := codeIndex(t, File{Path: "big.go", Text: b.String()})
	if x.Parents() < 3 || x.Len() < 42 {
		t.Fatalf("chunks %d, parents %d", x.Len(), x.Parents())
	}
	for _, parent := range x.parents {
		if len(parent.Text) > maxCodeParentBytes && !strings.HasPrefix(parent.Text, "func Long") && !strings.Contains(parent.Text, "\t_ = \"wwww") {
			t.Errorf("a parent of %d bytes: %.40q", len(parent.Text), parent.Text)
		}
	}
	for _, c := range x.chunks {
		if c.to-c.from > maxCodeChunkBytes {
			t.Errorf("a chunk of %d bytes", c.to-c.from)
		}
	}
}

// TestCutLinesKeepsALineLongerThanTheBoundWhole cuts a declaration whose one
// line is longer than a chunk: that line is a part alone, the others within
// the bound, and the parts hold the whole text in order.
func TestCutLinesKeepsALineLongerThanTheBoundWhole(t *testing.T) {
	text := "func F() {\n" + strings.Repeat("\t_ = 1\n", 600) + "\t_ = \"" + strings.Repeat("x", maxCodeChunkBytes+100) + "\"\n" + strings.Repeat("\t_ = 2\n", 600) + "}\n"
	parts := cutLines(text, 0, len(text))
	var joined strings.Builder
	long := 0
	for _, p := range parts {
		joined.WriteString(text[p[0]:p[1]])
		if p[1]-p[0] > maxCodeChunkBytes {
			long++
			if !strings.HasPrefix(text[p[0]:p[1]], "\t_ = \"xxx") {
				t.Errorf("a long part is not the long line: %.20q", text[p[0]:p[1]])
			}
		}
	}
	if joined.String() != text || long != 1 || len(parts) < 3 {
		t.Errorf("%d parts, %d long, whole text %v", len(parts), long, joined.String() == text)
	}
}
